import { type ComposedFeatures, NO_FEATURES } from "../features/registry";
import type { FeatureState } from "../features/types";
import type {
    AnyTypes,
    CheckMode,
    ChildrenStatus,
    DataOf,
    ItemFlags,
    KindOf,
    SelectionMode,
    TreeItem,
    TreeState,
    TreeTypes,
} from "./types";

/** `data` is optional exactly when the data type allows `undefined`. */
export type DataField<D> = undefined extends D ? { data?: D } : { data: D };

/** The fields an item is written with (in the document, `item.add`, `item.set-children`). */
export type TreeItemInit<K extends string = string, D = unknown> = {
    /** its id: the key of the document's `items` map (equal to it when given); generated by commands when missing */
    id?: string;
    kind: K;
    /** the item's name (the app renders it; the packages never do) */
    label: string;
    /** its children, in order; absent on a leaf */
    childItemIds?: string[];
    /** where its children come from the app's loader; absent when the item holds them itself */
    childrenStatus?: ChildrenStatus;
} & ItemFlags &
    DataField<D>;

/** An item of the registry `T` in JSON: a union over its kinds, so `data` is checked per kind. */
export type TreeItemJson<T extends TreeTypes = AnyTypes> = {
    [K in KindOf<T>]: TreeItemInit<K, DataOf<T, K>>;
}[KindOf<T>];

/** The tree's settings in JSON: each one optional (the defaults fill the rest). */
export interface TreeSettingsJson {
    selectionMode?: SelectionMode;
    checkMode?: CheckMode;
    /** the default of the items' `movable` flag */
    movable?: boolean;
    /** the default of the items' `renamable` flag */
    renamable?: boolean;
    /** the default of the items' `droppable` flag */
    droppable?: boolean;
}

/**
 * A tree document, version 1: what `createTreeModel` loads and `get("tree-json")` writes. A field
 * of a feature (`selectedItemIds`: `selection()`) loads only into a model with that feature.
 */
export interface TreeJson<T extends TreeTypes = AnyTypes> {
    version: 1;
    settings?: TreeSettingsJson;
    /** the root items, in order */
    rootItemIds: string[];
    /** every item, keyed by its id */
    items: Record<string, TreeItemJson<T>>;
    expandedItemIds?: string[];
    selectedItemIds?: string[];
    checkedItemIds?: string[];
    selectionAnchorItemId?: string | null;
    focusedItemId?: string | null;
    renamingItemId?: string | null;
}

/** A deep copy of a JSON value (the state is frozen; the document handed out is not). */
export function cloneJson<V>(value: V): V {
    return value === undefined
        ? value
        : (JSON.parse(JSON.stringify(value)) as V);
}

/** An item as JSON: a mutable copy with every field the item has, in a stable order. */
export function itemToJson(item: TreeItem): TreeItemInit {
    const json: TreeItemInit = {
        id: item.id,
        kind: item.kind,
        label: item.label,
    };
    if (item.data !== undefined) json.data = cloneJson(item.data);
    if (item.childItemIds !== undefined)
        json.childItemIds = [...item.childItemIds];
    if (item.childrenStatus !== undefined)
        json.childrenStatus = item.childrenStatus;
    if (item.disabled !== undefined) json.disabled = item.disabled;
    if (item.movable !== undefined) json.movable = item.movable;
    if (item.renamable !== undefined) json.renamable = item.renamable;
    if (item.droppable !== undefined) json.droppable = item.droppable;
    return json;
}

/** The document of a state: every field written, so a round trip is stable. */
export function stateToJson<T extends TreeTypes>(
    state: TreeState<T>,
    features: ComposedFeatures = NO_FEATURES,
): TreeJson<T> {
    const items: Record<string, TreeItemInit> = {};
    for (const [id, item] of Object.entries(state.items)) {
        items[id] = itemToJson(item);
    }
    return {
        version: 1,
        settings: { ...state.settings },
        rootItemIds: [...state.rootItemIds],
        items: items as Record<string, TreeItemJson<T>>,
        expandedItemIds: [...state.expandedItemIds],
        checkedItemIds: [...state.checkedItemIds],
        focusedItemId: state.focusedItemId,
        renamingItemId: state.renamingItemId,
        ...features.toJson(state as unknown as FeatureState),
    };
}
