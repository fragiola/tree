// The JSON Schemas of the tree document (version 1) and of the item fragments the commands reuse.
// Each one is self-contained (no `$ref`), so a command's schema can be handed as is to a tool.

/** An item id. */
export const idSchema = {
    type: "string",
    minLength: 1,
    description: "an item id",
} as const;

/** A list of item ids, none repeated. */
export const idListSchema = {
    type: "array",
    items: idSchema,
    uniqueItems: true,
    description: "item ids",
} as const;

/** An item id, or `null` for none. */
export const nullableIdSchema = {
    anyOf: [idSchema, { type: "null" }],
    description: "an item id, or null",
} as const;

export const childrenStatusSchema = {
    enum: ["unloaded", "loading", "loaded", "error"],
    description:
        "where the children come from the app's loader: unloaded, loading, loaded or error (absent: the item holds them itself)",
} as const;

/** The permission flags an item may set (the tree's settings give their defaults). */
export const itemFlagProperties = {
    disabled: {
        type: "boolean",
        description:
            "focusable but not actionable: no expand, select, check, rename, move or drop",
    },
    movable: {
        type: "boolean",
        description: "whether the item can be moved",
    },
    renamable: {
        type: "boolean",
        description: "whether the item's label can be edited",
    },
    droppable: {
        type: "boolean",
        description: "whether the item accepts items moved into it",
    },
} as const;

/** An item in JSON: in the document, and in `item.add` / `item.set-children`. */
export const itemJsonSchema = {
    type: "object",
    description: "an item",
    properties: {
        id: {
            type: "string",
            minLength: 1,
            description:
                "the item's id (in the document, the key of `items`; generated by a command when omitted)",
        },
        kind: {
            type: "string",
            minLength: 1,
            description: "what the item is (a key of the app's registry)",
        },
        label: {
            type: "string",
            description:
                "the item's name (the app renders it; the packages never do)",
        },
        data: { description: "the app's data (any JSON value)" },
        childItemIds: {
            type: "array",
            items: { type: "string", minLength: 1 },
            uniqueItems: true,
            description: "its children, in order (absent on a leaf)",
        },
        childrenStatus: childrenStatusSchema,
        ...itemFlagProperties,
    },
    required: ["kind", "label"],
    additionalProperties: false,
} as const;

export const settingsProperties = {
    selectionMode: {
        enum: ["none", "single", "multiple"],
        description: "how many items can be selected (default single)",
    },
    checkMode: {
        enum: ["cascade", "independent"],
        description:
            "cascade (default): checking a parent checks its descendants, a parent's state follows its children; independent: each item on its own",
    },
    movable: {
        type: "boolean",
        description: "the default of the items' movable flag (default true)",
    },
    renamable: {
        type: "boolean",
        description: "the default of the items' renamable flag (default true)",
    },
    droppable: {
        type: "boolean",
        description: "the default of the items' droppable flag (default true)",
    },
} as const;

/** The tree document, version 1. */
export const treeSchema = {
    $id: "https://fragiola.com/tree/schemas/tree-v1.json",
    title: "Fragiola Tree document",
    type: "object",
    properties: {
        version: { const: 1, description: "the document version" },
        settings: {
            type: "object",
            properties: settingsProperties,
            additionalProperties: false,
            description: "the tree's modes and the item flags' defaults",
        },
        rootItemIds: {
            ...idListSchema,
            description: "the root items, in order",
        },
        items: {
            type: "object",
            additionalProperties: itemJsonSchema,
            description: "every item, keyed by its id",
        },
        expandedItemIds: {
            ...idListSchema,
            description: "the expanded items",
        },
        selectedItemIds: {
            ...idListSchema,
            description: "the selected items",
        },
        checkedItemIds: {
            ...idListSchema,
            description: "the checked items",
        },
        selectionAnchorItemId: {
            ...nullableIdSchema,
            description: "where a range selection starts",
        },
        focusedItemId: {
            ...nullableIdSchema,
            description: "the roving tab stop",
        },
        renamingItemId: {
            ...nullableIdSchema,
            description: "the item being renamed",
        },
    },
    required: ["version", "rootItemIds", "items"],
    additionalProperties: false,
} as const;
